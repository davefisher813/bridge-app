import pw from "playwright";
const b=await pw.chromium.launch({executablePath:"/opt/pw-browsers/chromium",args:["--no-sandbox"]});
const ctx=await b.newContext({viewport:{width:1280,height:800}});const p=await ctx.newPage();
p.on("pageerror",e=>console.log("PAGEERR",String(e)));
p.on("console",m=>{if(m.type()==="error")console.log("CONSOLE",m.text().slice(0,200))});
await p.goto("http://localhost:3100/org/bridge-fixture/more",{waitUntil:"networkidle"});
await p.click('a[href="/org/bridge-fixture/documents"]');
await p.waitForURL("**/documents");
await p.waitForTimeout(1500);
await p.fill('input[name="q"]',"transcript");
await p.click('button:has-text("Search")');
await p.waitForTimeout(3000);
console.log(p.url());
console.log((await p.locator("main > div").first().innerText()).replace(/\n/g," | "));
